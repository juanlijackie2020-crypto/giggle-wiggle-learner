import { useMemo } from "react";
import { VoxelMesh, voxel as v, type Voxel } from "./VoxelMesh";
/** Original species-specific silhouettes; no imported game textures or models. */
export function animalVoxels(kind: number): Voxel[] {
  const p: Voxel[] = [];
  const add = (pos: Voxel["p"], size: Voxel["s"], c: string) =>
    p.push(v(pos, size, c));
  const eyes = (x: number, y: number, z: number) => {
    for (const side of [-1, 1]) {
      add([side * x, y, z], [0.1, 0.13, 0.035], "#26322c");
      add(
        [side * x - 0.018, y + 0.035, z - 0.02],
        [0.033, 0.038, 0.016],
        "#fffdf3",
      );
    }
  };
  if (kind === 0) {
    // Rabbit: haunches, long pink-lined ears, separate front paws.
    add([0, 0.38, 0.12], [0.55, 0.55, 0.68], "#ece4cf");
    add([0, 0.7, -0.3], [0.48, 0.46, 0.43], "#fff8e9");
    for (const side of [-1, 1]) {
      add([side * 0.26, 0.21, 0.26], [0.26, 0.36, 0.38], "#d8ceb6");
      add([side * 0.23, 0.08, 0.08], [0.24, 0.13, 0.5], "#f7efde");
      add([side * 0.16, 0.17, -0.34], [0.13, 0.28, 0.18], "#fff5e2");
      add([side * 0.15, 1.17, -0.23], [0.14, 0.63, 0.17], "#eee5d5");
      add([side * 0.15, 1.19, -0.322], [0.065, 0.43, 0.016], "#e9a4ac");
      add([side * 0.14, 0.55, -0.53], [0.16, 0.1, 0.08], "#f9f2dd");
    }
    eyes(0.13, 0.76, -0.522);
    add([0, 0.61, -0.57], [0.09, 0.07, 0.07], "#d78994");
    add([0, 0.38, 0.54], [0.25, 0.23, 0.23], "#fff8ec");
  } else if (kind === 1) {
    // Deer: long neck, branched antlers, spots, hooves.
    add([0, 0.91, 0.05], [0.64, 0.65, 1.12], "#bd8752");
    add([0, 0.81, -0.03], [0.45, 0.38, 0.95], "#dfb77e");
    add([0, 1.35, -0.42], [0.3, 0.85, 0.32], "#ba8658");
    add([0, 1.78, -0.58], [0.43, 0.42, 0.58], "#cf9b63");
    add([0, 1.67, -0.91], [0.32, 0.2, 0.22], "#ead3a0");
    add([0, 1.72, -1.03], [0.2, 0.12, 0.05], "#42382c");
    for (const side of [-1, 1]) {
      add([side * 0.28, 1.94, -0.55], [0.32, 0.14, 0.2], "#d5ac74");
      add([side * 0.18, 2.2, -0.45], [0.07, 0.53, 0.08], "#705034");
      add([side * 0.27, 2.31, -0.45], [0.24, 0.07, 0.08], "#89623e");
      add([side * 0.37, 2.4, -0.45], [0.07, 0.22, 0.08], "#89623e");
      for (const z of [-0.37, 0.45]) {
        add([side * 0.23, 0.38, z], [0.13, 0.78, 0.16], "#bc8753");
        add([side * 0.23, 0.06, z - 0.02], [0.18, 0.14, 0.22], "#483a30");
      }
      for (let i = 0; i < 5; i++)
        add(
          [side * 0.325, 1.03 + (i % 2) * 0.12, -0.31 + i * 0.18],
          [0.018, 0.085, 0.095],
          "#f9e4ac",
        );
    }
    eyes(0.125, 1.83, -0.88);
    add([0, 0.86, 0.87], [0.17, 0.17, 0.67], "#b37b45");
    add([0, 0.83, 1.18], [0.21, 0.21, 0.22], "#f3d7a1");
  } else if (kind === 2 || kind === 3) {
    const fox = kind === 3,
      coat = fox ? "#d97827" : "#ae6734",
      light = fox ? "#fff1d7" : "#efc58b";
    add([0, 0.45, 0], fox ? [0.53, 0.49, 0.95] : [0.46, 0.5, 0.61], coat);
    add([0, 0.37, -0.12], [0.39, 0.3, 0.48], light);
    add([0, 0.76, -0.45], [0.47, 0.4, 0.47], coat);
    add([0, 0.63, -0.73], [0.31, 0.21, 0.26], light);
    add([0, 0.66, -0.88], [0.16, 0.11, 0.07], "#302e2a");
    eyes(0.14, 0.8, -0.69);
    for (const side of [-1, 1]) {
      add([side * 0.17, 1.02, -0.43], [0.15, 0.28, 0.17], coat);
      add([side * 0.17, 1.05, -0.525], [0.08, 0.12, 0.025], "#443a32");
      for (const z of [-0.3, 0.3]) {
        add([side * 0.19, 0.16, z], [0.14, 0.32, 0.17], coat);
        add(
          [side * 0.19, 0.055, z - 0.025],
          [0.16, 0.12, 0.22],
          fox ? "#3b332e" : "#6a432d",
        );
      }
      add(
        [side * 0.245, 0.47, 0.02],
        [0.02, 0.1, 0.48],
        fox ? "#e6903a" : "#713e25",
      );
    }
    if (fox) {
      add([0, 0.45, 0.71], [0.33, 0.34, 0.67], coat);
      add([0, 0.44, 1.08], [0.31, 0.3, 0.24], "#fff0d5");
    } else {
      add([0, 0.68, 0.51], [0.36, 0.7, 0.36], "#85502f");
      add([0, 1.08, 0.55], [0.43, 0.37, 0.39], coat);
      add([0, 1.17, 0.35], [0.35, 0.25, 0.23], "#d49654");
    }
  } else if (kind === 4) {
    add([0, 0.38, 0], [0.34, 0.42, 0.52], "#388cbd");
    add([0, 0.34, -0.22], [0.26, 0.29, 0.18], "#ffd06c");
    add([0, 0.67, -0.21], [0.34, 0.32, 0.34], "#3a96c6");
    add([0, 0.61, -0.44], [0.15, 0.11, 0.2], "#e6a83c");
    eyes(0.09, 0.71, -0.389);
    for (const side of [-1, 1]) {
      add([side * 0.28, 0.43, 0.05], [0.3, 0.11, 0.49], "#23678d");
      add([side * 0.43, 0.4, 0.12], [0.16, 0.08, 0.36], "#8fd9e6");
      add([side * 0.1, 0.1, -0.03], [0.06, 0.18, 0.07], "#e3a13c");
      add([side * 0.1, 0.02, -0.1], [0.1, 0.05, 0.2], "#e3a13c");
    }
    add([0, 0.4, 0.4], [0.21, 0.1, 0.37], "#23678d");
  } else {
    add([0, 0.29, 0.1], [0.69, 0.48, 0.76], "#786047");
    add([0, 0.29, -0.4], [0.4, 0.3, 0.4], "#dab17c");
    add([0, 0.23, -0.64], [0.21, 0.17, 0.19], "#e7c08e");
    add([0, 0.25, -0.75], [0.1, 0.09, 0.06], "#342e28");
    eyes(0.13, 0.37, -0.605);
    for (const side of [-1, 1])
      for (const z of [-0.23, 0.36])
        add([side * 0.24, 0.07, z], [0.17, 0.12, 0.21], "#c69b6a");
    for (let i = 0; i < 25; i++)
      add(
        [
          ((i % 5) - 2) * 0.13,
          0.55 + ((i * 3) % 4) * 0.035,
          Math.floor(i / 5) * 0.14 - 0.2,
        ],
        [0.085, 0.2, 0.095],
        i % 2 ? "#d8ba83" : "#473d31",
      );
  }
  return p;
}
export function AnimalModel({ kind }: { kind: number }) {
  const parts = useMemo(() => animalVoxels(kind), [kind]);
  return <VoxelMesh parts={parts} />;
}
